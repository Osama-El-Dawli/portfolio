class ProfileEntity {
  final String name;
  final String title;
  final String email;
  final String phone;
  final String location;
  final String bio;
  final String linkedinUrl;
  final String githubUrl;
  final String avatarUrl;

  const ProfileEntity({
    required this.name,
    required this.title,
    required this.email,
    required this.phone,
    required this.location,
    required this.bio,
    required this.linkedinUrl,
    required this.githubUrl,
    required this.avatarUrl,
  });
}
